(() => {
  const $=s=>document.querySelector(s), results=[];
  const click=s=>{const el=$(s);if(!el)throw new Error('Missing: '+s);el.click();};
  const check=(condition,label)=>{if(!condition)throw new Error(label);results.push(label);};
  const action=a=>click(`[data-action="${a}"]`);
  action('close'); action('more'); action('reset'); action('confirm-reset');
  check($('#count').textContent==='(2款/2件)','Initial two products');
  click('.product:first-child .edit-product');
  check($('[data-action="minus"]').disabled,'Quantity minimum enforced');
  $('#price').value='-1'; action('confirm-edit');
  check(!$('#overlay').hidden,'Negative quote blocked');
  $('#price').value='28.50'; $('#minimum').value='100';$('#remark').value='需要绿色样布';
  action('requirement');action('plus');action('confirm-edit');
  check($('#count').textContent==='(2款/3件)','Quantity updates total');
  check($('.edit-product').textContent.includes('28.50'),'Quote saved');
  click('.product:first-child .edit-product');
  check($('#minimum').value==='100' && $('#remark').value==='需要绿色样布' && $('.requirement-grid .selected'),'Quote details retained');
  $('#price').value='50';action('close');click('.product:first-child .edit-product');
  check($('#price').value==='28.50','Closing discards unconfirmed edits');action('close');
  action('order');check($('#overlay').hidden,'Missing customer blocks order');
  action('text');action('recognize-text');check($('#text-error').textContent.length>0,'Invalid text extraction rejected');
  action('example');action('recognize-text');check($('#name').value==='陈晓' && $('#company').value==='云织服饰','Text extraction fills customer');
  action('customer');click('[data-index="1"]');check($('#name').value==='林悦','Customer picker works');
  action('card');action('recognize-card');check($('#card-error').textContent.length>0,'Card image required');
  const transfer=new DataTransfer();transfer.items.add(new File(['test'],'demo-card.png',{type:'image/png'}));$('#card-file').files=transfer.files;action('recognize-card');
  check($('#name').value==='陈晓','Card demo fills explicitly simulated data');
  action('save');const draft=JSON.parse(localStorage.getItem('cr-assisted-selection-v1'));
  check(draft.products[0].quantity===2 && draft.customer.name==='陈晓','Draft contains product and customer details');
  action('order');check($('#sheet').textContent.includes('确认提交'),'Order review shown');action('submit-order');
  check($('#sheet').textContent.includes('演示订单已创建'),'Demo order completed');action('close');
  action('clear');action('close');check($('.product'),'Clear cancellation retains products');
  action('clear');action('confirm-clear');check($('#count').textContent==='(0款/0件)' && $('.empty'),'Empty state works');
  action('order');check($('#overlay').hidden,'Empty order blocked');
  action('add');action('pick-product');check($('#count').textContent==='(1款/1件)','Adding product works');action('pick-product');
  check($('#count').textContent==='(1款/1件)','Duplicate product prevented');action('close');action('delete');check($('.empty'),'Delete works');
  return {passed:results.length,results};
})();
